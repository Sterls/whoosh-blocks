// Writes supabase/backfill_points.sql: gives every existing leaderboard entry
// the points the game itself credits for the levels they've beaten (base
// points per level), so switching the leaderboard from levels to points
// keeps everyone's position. Run with: node scripts/points-backfill.mjs
import { writeFileSync } from 'node:fs';
import { totalPoints } from '../js/points.js';

const MAX_LEVEL = 1000;
const rows = [];
for (let level = 1; level <= MAX_LEVEL; level++) {
  rows.push(`(${level},${totalPoints({ unlocked: level + 1, points: {} })})`);
}
const sql = `-- One-off: credit existing leaderboard entries with points for the levels
-- they've already beaten, so everyone keeps their position when the
-- leaderboard switches from levels to points. Run once in Supabase's SQL
-- Editor after setup.sql. Safe to run again: it only fills entries that
-- still have 0 points. Generated by scripts/points-backfill.mjs.

update public.scores s
set points = b.points
from (values
${rows.map((r, i) => (i % 10 === 0 ? '  ' : '') + r + (i < rows.length - 1 ? ',' : '') + (i % 10 === 9 ? '\n' : '')).join('').trimEnd()}
) as b (level, points)
where s.points = 0 and s.level = b.level;
`;
writeFileSync(new URL('../supabase/backfill_points.sql', import.meta.url), sql);
console.log(`wrote backfill for levels 1-${MAX_LEVEL}`);
